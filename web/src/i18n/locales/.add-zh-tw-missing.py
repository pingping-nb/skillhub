def apply_glossary(text: str) -> str:
    for src, dst in GLOSSARY:
        text = text.replace(src, dst)
    return text


def load(path):
    with open(path, encoding="utf-8-sig") as fh:
        return json.load(fh, object_pairs_hook=OrderedDict)


def flat(d, prefix=""):
    out = OrderedDict()
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flat(v, key + "."))
        else:
            out[key] = v
    return out


def set_path(root, dotted, value):
    parts = dotted.split(".")
    node = root
    for p in parts[:-1]:
        node = node.setdefault(p, OrderedDict())
    node[parts[-1]] = value


def main():
    en = flat(load(f"{LOCALES}/en.json"))
    zh = flat(load(f"{LOCALES}/zh.json"))
    tw_raw = load(f"{LOCALES}/zh-TW.json")
    tw = flat(tw_raw)

    missing = [k for k in en if k not in tw]
    added = 0
    for key in missing:
        if key in zh:
            value = apply_glossary(cc.convert(zh[key]))
        else:
            value = apply_glossary(cc.convert(en[key]))
        set_path(tw_raw, key, value)
        added += 1

    with open(f"{LOCALES}/zh-TW.json", "w", encoding="utf-8") as fh:
        json.dump(tw_raw, fh, ensure_ascii=False, indent=2)
        fh.write("\n")

    print(f"added {added} keys")


if __name__ == "__main__":
    main()
